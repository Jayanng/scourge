use cosmwasm_std::StdError;
use thiserror::Error;

#[derive(Error, Debug, PartialEq)]
pub enum ContractError {
    #[error("{0}")]
    Std(#[from] StdError),

    #[error("Unauthorized")]
    Unauthorized {},

    #[error("Invalid empty question")]
    EmptyQuestion {},

    #[error("closes_at must be in the future")]
    InvalidClosesAt {},
}
